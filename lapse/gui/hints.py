def _topic(key):
    t = TOPICS.get(key)
    if t is None:
        raise KeyError(f"没有这条参数讲解：{key}")
    return t


def line(key):
    """常驻在控件下面那一短行。"""
    return _topic(key)["line"]


def text(key, current=None):
    """tooltip 全文：干什么 / 怎么调 / 注意什么（+ 当前范围与默认值）。"""
    t = _topic(key)
    parts = [f"【{t['title']}】{t['what']}"]
    if t.get("how"):
        parts.append("怎么调：" + t["how"])
    if t.get("watch"):
        parts.append("注意：" + t["watch"])
    if current:
        parts.append(current)
    return "\n".join(parts)


def attach(widget, key, label=None, current=None):
    """把一条讲解挂到控件上：完整说明进 tooltip，标签共用同一份。

    短说明那行由界面代码传给 `field_block(..., hint=line(key))`——放哪儿、
    要不要放，是布局的决定，不该由文案层管。
    """
    tip = text(key, current)
    widget.setToolTip(tip)
    if label is not None:
        label.setToolTip(tip)
    return widget
